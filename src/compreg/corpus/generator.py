"""Deterministic generator for additional bounded test programs.

Programs are synthesized from an integer seed with a fixed PRNG. Semantics
are intentionally simple (integer arithmetic, reversal, gcd/lcm) so the
expected output can be computed by the generator with exact integer
semantics - the generated source's expected output is therefore derived
independently of any compiler.

All sources are valid C++17, terminate quickly, and never rely on undefined
behavior. Generated tests are written to the artifacts directory (never into
the repo's curated corpus) and are registered through their manifest file.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path
from typing import Callable, List, Optional

from ..models import OracleKind, OracleSpec, TestCase
from ..util import sha256_text

# A tiny deterministic PRNG (Numerical Recipes), replicated exactly so both
# generation rounds are reproducible.


class SeededRandom:
    """LCG with period 2^32; exact across Python versions and platforms."""

    def __init__(self, seed: int) -> None:
        if seed < 0:
            raise ValueError("seed must be non-negative")
        self._state = seed & 0xFFFFFFFF

    def next(self) -> int:
        self._state = (self._state * 1664525 + 1013904223) & 0xFFFFFFFF
        return self._state

    def below(self, bound: int) -> int:
        if bound <= 0:
            raise ValueError("bound must be positive")
        return self.next() % bound


GENERATED_DIRNAME = "generated"


@dataclass(frozen=True)
class GeneratedTest:
    """A generator-produced test with its precomputed oracle."""

    test_case: TestCase
    manifest_path: str


# --------------------------------------------------------------------- #
# program templates. Each returns (source_text, expected_stdout) using
# integer-only math.
# --------------------------------------------------------------------- #
def _program_sum_squares(n: int) -> tuple[str, str]:
    assert 1 <= n <= 60
    expected_total = n * (n + 1) * (2 * n + 1) // 6
    source = f"""// Generated compreg test: gen_sum_squares_{n}.
// Prints the sum of i*i for i = 1..{n} (loop-recomputed, no overflow: the
// maximum term ~ n^3 << 2^63) and the closed form for cross-checking.
#include <cstdio>

int main() {{
    const int n = {n};
    long long total = 0;
    for (int i = 1; i <= n; ++i) {{
        total += static_cast<long long>(i) * i;
    }}
    const long long formula = static_cast<long long>(n) * (n + 1) * (2 * n + 1) / 6;
    std::printf("%lld\\n", total);
    std::printf("%lld\\n", formula);
    return (total == formula) ? 0 : 1;
}}
"""
    return source, f"{expected_total}\n{expected_total}\n"


def _program_reverse_sequence(n: int, seed_value: int) -> tuple[str, str]:
    assert 5 <= n <= 24
    rng = SeededRandom(seed_value)
    values = [rng.below(1000) for _ in range(n)]
    cpp_values = ", ".join(str(v) for v in values)
    # The program prints "%d " tokens; the expected output is space-separated.
    expected_tokens = " ".join(str(v) for v in reversed(values))
    source = f"""// Generated compreg test: gen_reverse_{n}_{seed_value & 0xFFFF}.
// Reverses a fixed n={n} vector and prints it; expected output is
// precomputed by the generator with exact integer semantics.
#include <cstdio>

int main() {{
    const int data[{n}] = {{ {cpp_values} }};
    int reversed[{n}];
    for (int i = 0; i < {n}; ++i) {{
        reversed[i] = data[{n} - 1 - i];
    }}
    for (int i = 0; i < {n}; ++i) {{
        std::printf("%d ", reversed[i]);
    }}
    std::printf("\\n");
    return 0;
}}
"""
    return source, expected_tokens + " \n"


def _program_gcd_lcm(a: int, b: int) -> tuple[str, str]:
    # a and b are in 2..997, generated by the caller.
    assert 2 <= a <= 997 and 2 <= b <= 997

    def gcd(x: int, y: int) -> int:
        while y:
            x, y = y, x % y
        return x

    g = gcd(a, b)
    l = a // g * b  # no overflow: <= 994009 fits any 32-bit type anyway
    source = f"""// Generated compreg test: gen_gcd_lcm_{a}_{b}.
// Euclid's algorithm plus lcm; expected values computed by the generator.
#include <cstdio>

static long long gcd_ll(long long x, long long y) {{
    long long a = x;
    long long b = y;
    while (b != 0) {{
        const long long t = a % b;
        a = b;
        b = t;
    }}
    return a;
}}

int main() {{
    const long long a = {a};
    const long long b = {b};
    const long long g = gcd_ll(a, b);
    const long long l = a / g * b;
    std::printf("%lld\\n", g);
    std::printf("%lld\\n", l);
    return 0;
}}
"""
    return source, f"{g}\n{l}\n"


_GENERATORS: dict[str, Callable[[tuple[int, ...]], tuple[str, str]]] = {
    "sum_squares": lambda args: _program_sum_squares(args[0]),
    "reverse": lambda args: _program_reverse_sequence(args[0], args[1]),
    "gcd_lcm": lambda args: _program_gcd_lcm(args[0], args[1]),
}


def generate_program(kind: str, rng: SeededRandom) -> tuple[str, str, str]:
    """Generate `(kind, source, expected)` for one seeded program kind.

    Inputs are kept small so every program terminates in microseconds.
    """
    if kind == "sum_squares":
        source, expected = _GENERATORS[kind]((1 + rng.below(60),))
    elif kind == "reverse":
        source, expected = _GENERATORS[kind]((5 + rng.below(20), rng.next()))
    elif kind == "gcd_lcm":
        source, expected = _GENERATORS[kind]((2 + rng.below(995), 2 + rng.below(995)))
    else:
        raise ValueError(f"unknown generator kind '{kind}'")
    return kind, source, expected


def program_test_id(kind: str, seed: int, index: int) -> str:
    """Stable identifier encoding kind + seed, deterministic per seed."""
    return f"generated_{kind}_{seed}_{index}"


def generate_corpus(
    count: int,
    seed: int,
    output_dir: Path,
    kinds_order: List[str] | None = None,
) -> List[GeneratedTest]:
    """Generate `count` programs under `output_dir`, returning registry entries.

    Deterministic: given (count, kind order, seed) the sources and expected
    outputs are byte-identical on every platform. Registration happens
    through the returned manifest, not by mutating the curated corpus.
    """
    if count < 1:
        raise ValueError("count must be >= 1")
    kinds = kinds_order or ["sum_squares", "reverse", "gcd_lcm"]
    operations_dir = output_dir / GENERATED_DIRNAME
    operations_dir.mkdir(parents=True, exist_ok=True)

    manifest: List[GeneratedTest] = []
    manifest_entries: List[dict] = []
    rng = SeededRandom(seed)
    for index in range(count):
        kind = kinds[index % len(kinds)]
        program_kind, source, expected = generate_program(kind, rng)
        test_id = program_test_id(kind, seed, index)
        source_path = operations_dir / f"{test_id}.cpp"
        expected_path = operations_dir / f"{test_id}.expected"
        source_path.write_text(source, encoding="utf-8")
        expected_path.write_text(expected, encoding="utf-8")
        test_case = TestCase(
            test_id=test_id,
            source_path=str(source_path),
            category="generated",
            description=f"generated {kind} program (seed={seed}, index={index})",
            oracle=OracleSpec(kind=OracleKind.EXACT, expected_stdout=expected, tolerance=0),
            timeout_s=10.0,
        )
        manifest.append(GeneratedTest(test_case=test_case, manifest_path=str(expected_path)))
        manifest_entries.append(
            {"test_id": test_id, "kind": kind, "source": str(source_path),
             "expected": str(expected_path), "seed": seed}
        )

    write_manifest(manifest_entries, operations_dir / "manifest.json")
    return manifest


def write_manifest(entries: List[dict], path: Path) -> None:
    path.write_text(json.dumps(entries, indent=2, sort_keys=True), encoding="utf-8")


def load_manifest(path: str | Path, project_root: Optional[Path] = None) -> List[TestCase]:
    """Load generated tests from a `generate` invocation's manifest file."""
    if project_root is None:
        project_root = Path(__file__).resolve().parents[3]
    manifest_path = Path(path)
    if not manifest_path.is_file():
        raise FileNotFoundError(f"generated-test manifest not found: {manifest_path}")
    tests: List[TestCase] = []
    for entry in json.loads(manifest_path.read_text(encoding="utf-8")):
        source = Path(entry["source"])
        if not source.is_absolute():
            source = project_root / source
        expected_path = Path(entry["expected"])
        if not expected_path.is_absolute():
            expected_path = project_root / expected_path
        expected = expected_path.read_text(encoding="utf-8")
        tests.append(
            TestCase(
                test_id=entry["test_id"],
                source_path=str(source),
                category="generated",
                description=f"generated {entry['kind']} program (seed={entry['seed']})",
                oracle=OracleSpec(kind=OracleKind.EXACT, expected_stdout=expected, tolerance=0),
                timeout_s=10.0,
            )
        )
    return tests


def corpus_hash(test: TestCase) -> str:
    return sha256_text(test.test_id + "|" + test.source_path + "|" + test.oracle.expected_stdout)
